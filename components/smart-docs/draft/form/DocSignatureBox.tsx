'use client';

import React, { useRef, useState, useEffect, useCallback } from 'react';
import { formatSignatureUrl } from '@/lib/api/smart-docs.service';
import { fetchSignatureAsDataUrlAction } from '@/app/actions/smart-docs';

export interface DocSignatureBoxProps {
  partyType?: 'importer' | 'exporter' | 'broker' | string;
  title?: string;
  onTitleChange?: (val: string) => void;
  titleAsText?: boolean;
  signatureUrl: string;
  onSignatureChange: (url: string) => void;
  authorityTitle?: string;
  onAuthorityTitleChange?: (val: string) => void;
  authorityError?: string | null;
  titlePlaceholder?: string;
  authorityPlaceholder?: string;
  readOnly?: boolean;
  className?: string;
  uploadButtonLabel?: string;
  clearButtonLabel?: string;
  error?: string | null;
  hideTitleFields?: boolean;
}

// Standard professional trade blue ink color
const STANDARD_PEN_COLOR = '#0284c7';

interface Point {
  x: number; // 0..1 normalized
  y: number; // 0..1 normalized
}

interface Stroke {
  points: Point[];
  color: string;
}

// Robust helper to extract points from any stroke representation (new object format or legacy array)
function getStrokePoints(stroke: any): Point[] {
  if (!stroke) return [];
  if (Array.isArray(stroke.points)) return stroke.points;
  if (Array.isArray(stroke)) return stroke;
  return [];
}

function drawStrokesToContext(
  ctx: CanvasRenderingContext2D,
  strokes: Stroke[],
  w: number,
  h: number,
  fallbackColor: string = STANDARD_PEN_COLOR
) {
  if (!strokes || !Array.isArray(strokes) || strokes.length === 0) return;

  try {
    ctx.save();
    ctx.lineWidth = 2.5;
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';

    for (const stroke of strokes) {
      const points = getStrokePoints(stroke);
      if (!points || points.length === 0) continue;
      const color = stroke?.color || fallbackColor;
      ctx.strokeStyle = color;
      ctx.fillStyle = color;

      const first = points[0];
      if (!first || typeof first.x !== 'number' || typeof first.y !== 'number') continue;

      if (points.length === 1) {
        ctx.beginPath();
        ctx.arc(first.x * w, first.y * h, 1.25, 0, Math.PI * 2);
        ctx.fill();
        continue;
      }

      ctx.beginPath();
      ctx.moveTo(first.x * w, first.y * h);
      for (let i = 1; i < points.length; i++) {
        const pt = points[i];
        if (pt && typeof pt.x === 'number' && typeof pt.y === 'number') {
          ctx.lineTo(pt.x * w, pt.y * h);
        }
      }
      ctx.stroke();
    }
  } catch (err) {
    console.warn('[DocSignatureBox] Error drawing strokes to context:', err);
  } finally {
    try {
      ctx.restore();
    } catch {}
  }
}

export function DocSignatureBox({
  partyType = 'exporter',
  title = '',
  onTitleChange = () => {},
  titleAsText = false,
  signatureUrl,
  onSignatureChange,
  authorityTitle = '',
  onAuthorityTitleChange = () => {},
  authorityError = null,
  titlePlaceholder,
  authorityPlaceholder,
  readOnly = false,
  className = '',
  error = null,
  hideTitleFields = false,
}: DocSignatureBoxProps) {
  const titleInputRef = useRef<HTMLInputElement>(null);
  const authTitleInputRef = useRef<HTMLInputElement>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);
  const colorInputRef = useRef<HTMLInputElement>(null);

  const containerRef = useRef<HTMLDivElement>(null);
  const canvasRef = useRef<HTMLCanvasElement | null>(null);

  // User-selected ink color (defaults directly to trade blue #0284c7)
  const [penColor, setPenColor] = useState<string>(STANDARD_PEN_COLOR);
  const penColorRef = useRef<string>(STANDARD_PEN_COLOR);

  useEffect(() => {
    penColorRef.current = penColor;
  }, [penColor]);

  // Tracks the last exported data URL generated by this component to avoid echoing
  const lastExportedUrlRef = useRef<string>('');

  // Server-provided signature image URL (prefixed with assets CDN domain)
  const [serverImageUrl, setServerImageUrl] = useState<string>(() => {
    return formatSignatureUrl(signatureUrl);
  });

  // Local uploaded stamp/signature data URL (when user uploads an image file)
  const [uploadedStampSrc, setUploadedStampSrc] = useState<string>('');

  // Unified base image element (loaded stamp from mobile API or local file upload)
  const baseImageObjRef = useRef<HTMLImageElement | null>(null);

  // Hand-drawn signature strokes (array of stroke paths, normalized 0..1 with individual ink colors)
  const strokesRef = useRef<Stroke[]>([]);
  const [hasDrawnSignature, setHasDrawnSignature] = useState<boolean>(false);
  const [isDrawingMode, setIsDrawingMode] = useState<boolean>(false);
  const [isLoadingBaseImage, setIsLoadingBaseImage] = useState<boolean>(false);

  // Active stroke drawing refs (universal pointer capture)
  const isPointerDownRef = useRef<boolean>(false);
  const currentStrokeRef = useRef<Point[]>([]);

  // Redraw both the base stamp image AND hand-drawn strokes onto the unified canvas
  const redrawCanvas = useCallback(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    const rect = canvas.getBoundingClientRect();
    if (rect.width === 0 || rect.height === 0) return;

    const dpr = typeof window !== 'undefined' ? window.devicePixelRatio || 1 : 1;
    const w = rect.width;
    const h = rect.height;
    const targetW = Math.round(w * dpr);
    const targetH = Math.round(h * dpr);

    if (canvas.width !== targetW || canvas.height !== targetH) {
      canvas.width = targetW;
      canvas.height = targetH;
    }

    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.clearRect(0, 0, w, h);

    // 1. Draw base image (stamp / loaded signature from mobile) if present
    const baseImg = baseImageObjRef.current;
    if (baseImg && baseImg.complete && baseImg.naturalWidth > 0 && baseImg.naturalHeight > 0) {
      try {
        const pad = 12;
        const availW = Math.max(10, w - pad * 2);
        const availH = Math.max(10, h - pad * 2);
        const imgW = baseImg.naturalWidth;
        const imgH = baseImg.naturalHeight;
        const scale = Math.min(availW / imgW, availH / imgH);
        const drawW = imgW * scale;
        const drawH = imgH * scale;
        const drawX = pad + (availW - drawW) / 2;
        const drawY = pad + (availH - drawH) / 2;

        ctx.drawImage(baseImg, drawX, drawY, drawW, drawH);
      } catch (err) {
        console.warn('[DocSignatureBox] Error drawing base image to canvas:', err);
      }
    }

    // 2. Draw user hand-drawn strokes directly on top of base image
    drawStrokesToContext(ctx, strokesRef.current, w, h, penColorRef.current);
  }, []);

  // Export current unified canvas signature to parent
  const exportCanvasSignature = useCallback(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;

    // If user drew strokes, export full unified canvas (base stamp + hand-drawn signature)
    if (strokesRef.current.length > 0) {
      try {
        const dataUrl = canvas.toDataURL('image/png');
        lastExportedUrlRef.current = dataUrl;
        onSignatureChange(dataUrl);
        return;
      } catch (err) {
        console.warn('[DocSignatureBox] toDataURL export failed:', err);
      }
    }

    // If no strokes drawn, but user uploaded a new stamp file:
    if (uploadedStampSrc) {
      lastExportedUrlRef.current = uploadedStampSrc;
      onSignatureChange(uploadedStampSrc);
      return;
    }

    // If no strokes drawn, but initial server image exists:
    if (serverImageUrl) {
      lastExportedUrlRef.current = serverImageUrl;
      onSignatureChange(serverImageUrl);
      return;
    }

    // Completely empty
    lastExportedUrlRef.current = '';
    onSignatureChange('');
  }, [uploadedStampSrc, serverImageUrl, onSignatureChange]);

  // Load a base image (data URL or external URL) into baseImageObjRef
  const loadBaseImage = useCallback(
    (src: string, onLoaded?: () => void) => {
      if (!src) {
        baseImageObjRef.current = null;
        setIsLoadingBaseImage(false);
        redrawCanvas();
        if (onLoaded) onLoaded();
        return;
      }

      const img = new Image();
      if (!src.startsWith('data:') && !src.startsWith('blob:')) {
        img.crossOrigin = 'anonymous';
      }
      img.onload = () => {
        baseImageObjRef.current = img;
        setIsLoadingBaseImage(false);
        redrawCanvas();
        if (onLoaded) onLoaded();
      };
      img.onerror = (err) => {
        // If crossOrigin='anonymous' caused CORS failure on remote asset, retry directly without crossOrigin
        if (img.crossOrigin) {
          const fallbackImg = new Image();
          fallbackImg.onload = () => {
            baseImageObjRef.current = fallbackImg;
            setIsLoadingBaseImage(false);
            redrawCanvas();
            if (onLoaded) onLoaded();
          };
          fallbackImg.onerror = (fallbackErr) => {
            console.warn('[DocSignatureBox] Base image fallback load error:', src, fallbackErr);
            baseImageObjRef.current = null;
            setIsLoadingBaseImage(false);
            redrawCanvas();
            if (onLoaded) onLoaded();
          };
          fallbackImg.src = src;
          return;
        }
        console.warn('[DocSignatureBox] Base image load error:', src, err);
        baseImageObjRef.current = null;
        setIsLoadingBaseImage(false);
        redrawCanvas();
        if (onLoaded) onLoaded();
      };
      img.src = src;
    },
    [redrawCanvas]
  );

  // Synchronize incoming signatureUrl from parent/API
  useEffect(() => {
    // If incoming signatureUrl is our own recent export, ignore to prevent duplicate rendering
    if (signatureUrl && signatureUrl === lastExportedUrlRef.current) {
      return;
    }

    // If cleared externally from parent
    if (!signatureUrl) {
      setServerImageUrl('');
      setUploadedStampSrc('');
      baseImageObjRef.current = null;
      strokesRef.current = [];
      setHasDrawnSignature(false);
      setIsDrawingMode(false);
      setIsLoadingBaseImage(false);
      lastExportedUrlRef.current = '';
      redrawCanvas();
      return;
    }

    // A fresh signature URL arrived from external / API / post-save confirmation:
    // Important: Clear strokes overlay because the new server image already contains all previous edits baked in!
    strokesRef.current = [];
    setHasDrawnSignature(false);

    const formatted = formatSignatureUrl(signatureUrl);
    setServerImageUrl(formatted);

    if (!formatted) {
      setServerImageUrl('');
      setUploadedStampSrc('');
      baseImageObjRef.current = null;
      strokesRef.current = [];
      setHasDrawnSignature(false);
      setIsDrawingMode(false);
      setIsLoadingBaseImage(false);
      lastExportedUrlRef.current = '';
      redrawCanvas();
      return;
    }

    // If already data: or blob:, load directly
    if (formatted.startsWith('data:') || formatted.startsWith('blob:')) {
      setIsLoadingBaseImage(false);
      loadBaseImage(formatted);
      return;
    }

    // If remote HTTP/HTTPS URL (e.g. from mobile app), securely fetch as Data URL via server action
    // to eliminate browser CORS restrictions and prevent tainted canvas SecurityErrors.
    let isCancelled = false;
    setIsLoadingBaseImage(true);

    const safetyTimer = setTimeout(() => {
      if (!isCancelled) {
        setIsLoadingBaseImage(false);
        loadBaseImage(formatted);
      }
    }, 2500);

    fetchSignatureAsDataUrlAction(formatted)
      .then((dataUrl) => {
        clearTimeout(safetyTimer);
        if (isCancelled) return;
        setIsLoadingBaseImage(false);
        if (dataUrl) {
          loadBaseImage(dataUrl);
        } else {
          loadBaseImage(formatted);
        }
      })
      .catch(() => {
        clearTimeout(safetyTimer);
        if (!isCancelled) {
          setIsLoadingBaseImage(false);
          loadBaseImage(formatted);
        }
      });

    return () => {
      isCancelled = true;
      clearTimeout(safetyTimer);
      setIsLoadingBaseImage(false);
    };
  }, [signatureUrl, loadBaseImage, redrawCanvas]);

  // Sync canvas size on mount, window resize, or container dimension changes
  const syncCanvasSize = useCallback(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;

    const rect = canvas.getBoundingClientRect();
    if (rect.width === 0 || rect.height === 0) return;

    const dpr = typeof window !== 'undefined' ? window.devicePixelRatio || 1 : 1;
    const targetW = Math.round(rect.width * dpr);
    const targetH = Math.round(rect.height * dpr);

    if (canvas.width !== targetW || canvas.height !== targetH) {
      canvas.width = targetW;
      canvas.height = targetH;
    }
    redrawCanvas();
  }, [redrawCanvas]);

  useEffect(() => {
    const container = containerRef.current;
    if (!container) return;

    let resizeObserver: ResizeObserver | null = null;
    if (typeof ResizeObserver !== 'undefined') {
      resizeObserver = new ResizeObserver(() => {
        syncCanvasSize();
      });
      resizeObserver.observe(container);
    }

    syncCanvasSize();
    const handleResize = () => syncCanvasSize();
    window.addEventListener('resize', handleResize);

    return () => {
      if (resizeObserver) resizeObserver.disconnect();
      window.removeEventListener('resize', handleResize);
    };
  }, [syncCanvasSize]);

  // Normalize pointer coordinates to 0..1 range
  const getNormalizedPoint = (e: React.PointerEvent<HTMLCanvasElement>): Point | null => {
    const canvas = canvasRef.current;
    if (!canvas) return null;
    const rect = canvas.getBoundingClientRect();
    if (rect.width === 0 || rect.height === 0) return null;

    const x = Math.max(0, Math.min(1, (e.clientX - rect.left) / rect.width));
    const y = Math.max(0, Math.min(1, (e.clientY - rect.top) / rect.height));

    return { x, y };
  };

  // Start Drawing Stroke (Mouse, Touch, Stylus)
  const handlePointerDown = (e: React.PointerEvent<HTMLCanvasElement>) => {
    if (readOnly) return;
    try {
      e.currentTarget.setPointerCapture(e.pointerId);
    } catch {}

    const pt = getNormalizedPoint(e);
    if (!pt) return;

    isPointerDownRef.current = true;
    setIsDrawingMode(true);
    currentStrokeRef.current = [pt];

    // Live canvas dot drawing with active pen color for immediate zero-latency feedback
    const canvas = canvasRef.current;
    if (!canvas) return;
    const rect = canvas.getBoundingClientRect();
    const ctx = canvas.getContext('2d');
    if (ctx) {
      const dpr = typeof window !== 'undefined' ? window.devicePixelRatio || 1 : 1;
      const activeColor = penColorRef.current;
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      ctx.strokeStyle = activeColor;
      ctx.fillStyle = activeColor;
      ctx.lineWidth = 2.5;
      ctx.lineCap = 'round';
      ctx.lineJoin = 'round';

      ctx.beginPath();
      ctx.arc(pt.x * rect.width, pt.y * rect.height, 1.25, 0, Math.PI * 2);
      ctx.fill();
      ctx.beginPath();
      ctx.moveTo(pt.x * rect.width, pt.y * rect.height);
    }
  };

  // Continue Drawing Stroke
  const handlePointerMove = (e: React.PointerEvent<HTMLCanvasElement>) => {
    if (!isPointerDownRef.current || readOnly) return;
    const pt = getNormalizedPoint(e);
    if (!pt) return;

    currentStrokeRef.current.push(pt);

    const canvas = canvasRef.current;
    if (!canvas) return;
    const rect = canvas.getBoundingClientRect();
    const ctx = canvas.getContext('2d');
    if (ctx) {
      const dpr = typeof window !== 'undefined' ? window.devicePixelRatio || 1 : 1;
      const activeColor = penColorRef.current;
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
      ctx.strokeStyle = activeColor;
      ctx.lineWidth = 2.5;
      ctx.lineCap = 'round';
      ctx.lineJoin = 'round';

      ctx.lineTo(pt.x * rect.width, pt.y * rect.height);
      ctx.stroke();
    }
  };

  // End Drawing Stroke
  const handlePointerUp = (e: React.PointerEvent<HTMLCanvasElement>) => {
    if (!isPointerDownRef.current) return;
    isPointerDownRef.current = false;
    try {
      e.currentTarget.releasePointerCapture(e.pointerId);
    } catch {}

    if (currentStrokeRef.current.length > 0) {
      const newStroke: Stroke = {
        points: [...currentStrokeRef.current],
        color: penColorRef.current,
      };
      strokesRef.current.push(newStroke);
      currentStrokeRef.current = [];
      setHasDrawnSignature(true);
      redrawCanvas();
      exportCanvasSignature();
    }
  };

  // Upload New Stamp / Signature Image
  const handleStampUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    const reader = new FileReader();
    reader.onload = (uploadEvt) => {
      const res = uploadEvt.target?.result;
      if (typeof res !== 'string') return;

      setUploadedStampSrc(res);
      loadBaseImage(res, () => {
        exportCanvasSignature();
      });
    };
    reader.readAsDataURL(file);
    e.target.value = '';
  };

  // Undo last drawn stroke
  const handleUndo = () => {
    if (strokesRef.current.length === 0) return;
    strokesRef.current.pop();
    if (strokesRef.current.length === 0) {
      setHasDrawnSignature(false);
    }
    redrawCanvas();
    exportCanvasSignature();
  };

  // Clear hand-drawn strokes only (Base stamp/image from mobile or upload is 100% preserved)
  const handleClearSignature = () => {
    strokesRef.current = [];
    setHasDrawnSignature(false);
    redrawCanvas();
    exportCanvasSignature();
  };

  // Clear everything (both stamp/image and drawn strokes)
  const handleClearAll = () => {
    setUploadedStampSrc('');
    setServerImageUrl('');
    baseImageObjRef.current = null;
    strokesRef.current = [];
    setHasDrawnSignature(false);
    setIsDrawingMode(false);
    lastExportedUrlRef.current = '';
    redrawCanvas();
    onSignatureChange('');
  };

  // Activate / Focus drawing mode
  const handleActivateDrawing = () => {
    if (readOnly) return;
    setIsDrawingMode(true);
    containerRef.current?.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
  };

  // Determine if there is any visible content (either base stamp or drawn strokes)
  const hasBaseImage = Boolean(uploadedStampSrc || baseImageObjRef.current || (serverImageUrl && isLoadingBaseImage));
  const hasAnyContent = Boolean(hasBaseImage || hasDrawnSignature || strokesRef.current.length > 0);

  return (
    <div className={`p-3 sm:p-4 flex flex-col items-center w-full ${className}`}>
      {/* Top Header: Title with dotted underline & edit pencil or plain text */}
      {!hideTitleFields && (
        <div className="flex items-center justify-center gap-1.5 w-full">
          {titleAsText ? (
            <div className="font-bold text-center tracking-wider text-[14px] uppercase text-foreground py-0.5 px-2 select-all">
              {title ||
                titlePlaceholder ||
                (partyType === 'exporter'
                  ? 'SELLER / EXPORTER'
                  : partyType === 'broker'
                  ? 'BROKER'
                  : 'BUYER / IMPORTER')}
            </div>
          ) : (
            <>
              <input
                ref={titleInputRef}
                type="text"
                value={title}
                onChange={(e) => onTitleChange(e.target.value)}
                disabled={readOnly}
                aria-label={`${partyType} title`}
                placeholder={
                  titlePlaceholder ||
                  (partyType === 'exporter'
                    ? 'Seller / Exporter'
                    : partyType === 'broker'
                    ? 'Broker'
                    : 'Buyer / Importer')
                }
                className="font-bold text-center tracking-wider text-[14px] bg-transparent border-b-2 border-dotted border-primary/60 hover:border-primary focus:border-solid focus:border-primary focus:outline-none text-foreground py-0.5 px-2 w-full max-w-[280px] sm:max-w-[340px] transition-colors placeholder:text-[14px] placeholder:font-normal placeholder:text-muted-foreground/50"
              />
              {!readOnly && (
                <button
                  type="button"
                  onClick={() => titleInputRef.current?.focus()}
                  title="Edit title"
                  className="text-primary hover:text-primary-hover transition-colors p-0.5 cursor-pointer disabled:opacity-40"
                >
                  <i className="fa-solid fa-pen text-xs" />
                </button>
              )}
            </>
          )}
        </div>
      )}

      {/* Signature & Stamp Multi-Layer Unified Interactive Box */}
      <div
        ref={containerRef}
        className={`w-full h-40 sm:h-48 my-2 rounded-lg bg-background dark:bg-card border-2 transition-all flex items-center justify-center relative overflow-hidden shadow-2xs group select-none ${
          error
            ? 'border-brand-red ring-1 ring-brand-red/30 border-solid'
            : isDrawingMode
            ? 'border-primary ring-2 ring-primary/25 border-dashed'
            : 'border-border hover:border-primary/50 border-dashed'
        }`}
      >
        {/* Loading spinner when securely fetching remote mobile stamp */}
        {isLoadingBaseImage && !baseImageObjRef.current && (
          <div className="absolute inset-0 z-4 flex items-center justify-center bg-background/50 backdrop-blur-2xs">
            <i className="fa-solid fa-circle-notch fa-spin text-primary text-xl" />
          </div>
        )}

        {/* UNIFIED CANVAS: Renders both base stamp image AND hand-drawn strokes with zero offset discrepancy */}
        <canvas
          ref={canvasRef}
          style={{ touchAction: 'none' }}
          className={`w-full h-full touch-none select-none relative z-2 ${
            readOnly ? 'cursor-default' : 'cursor-crosshair'
          }`}
          onPointerDown={handlePointerDown}
          onPointerMove={handlePointerMove}
          onPointerUp={handlePointerUp}
          onPointerCancel={handlePointerUp}
        />

        {/* Empty Canvas Prompt / Instructions (Visible ONLY when no signature or stamp exists) */}
        {!hasAnyContent && !isLoadingBaseImage && (
          <div className="absolute inset-0 pointer-events-none flex flex-col items-center justify-center text-muted-foreground/75 select-none p-3 text-center z-3">
            <div className="w-10 h-10 rounded-full bg-primary/10 text-primary flex items-center justify-center mb-1.5 shadow-2xs">
              <i className="fa-solid fa-pen-nib text-base" />
            </div>
            <span className="text-xs sm:text-sm font-bold text-foreground/90">
              Draw Signature Directly Here
            </span>
            <span className="text-[11px] text-muted-foreground mt-0.5">
              Sign with mouse, trackpad, or finger &bull; Or upload stamp below
            </span>
          </div>
        )}

        {/* Canvas Quick Tools: Undo / Clear for hand-drawn signature */}
        {hasDrawnSignature && !readOnly && (
          <div className="absolute top-2 right-2 flex items-center gap-1 z-10 bg-background/90 dark:bg-card/90 backdrop-blur-xs p-1 rounded-md border border-border/80 shadow-xs">
            <button
              type="button"
              onClick={handleUndo}
              title="Undo last stroke"
              aria-label="Undo last stroke"
              className="w-6 h-6 flex items-center justify-center rounded text-muted-foreground hover:text-foreground hover:bg-muted text-xs transition-colors cursor-pointer"
            >
              <i className="fa-solid fa-rotate-left text-[11px]" />
            </button>
            <button
              type="button"
              onClick={handleClearSignature}
              title="Clear signature strokes"
              aria-label="Clear signature strokes"
              className="w-6 h-6 flex items-center justify-center rounded text-muted-foreground hover:text-destructive hover:bg-destructive/10 text-xs transition-colors cursor-pointer"
            >
              <i className="fa-solid fa-eraser text-[11px]" />
            </button>
          </div>
        )}
      </div>

      {/* Action Controls Toolbar: Clean buttons with contextual Draw, Direct Ink Color Picker, Upload, and Clear controls */}
      <div className="flex items-center justify-center gap-2 sm:gap-3 w-full px-0.5 my-2 flex-wrap">
        <input
          ref={fileInputRef}
          type="file"
          accept="image/*"
          className="hidden"
          onChange={handleStampUpload}
        />
        <button
          type="button"
          disabled={readOnly}
          onClick={() => fileInputRef.current?.click()}
          className="px-3 py-1.5 rounded-md border border-border/80 bg-card hover:bg-muted text-foreground text-xs font-medium shadow-2xs hover:shadow-xs transition-colors cursor-pointer flex items-center gap-1.5 disabled:opacity-40 disabled:cursor-not-allowed"
        >
          <i className="fa-solid fa-stamp text-[11px] text-muted-foreground" />
          <span>Upload Stamp / Signature</span>
        </button>

        <button
          type="button"
          disabled={readOnly}
          onClick={handleActivateDrawing}
          className={`px-3 py-1.5 rounded-md border text-xs font-medium shadow-2xs hover:shadow-xs transition-colors cursor-pointer flex items-center gap-1.5 disabled:opacity-40 disabled:cursor-not-allowed ${
            isDrawingMode
              ? 'border-primary bg-primary/10 text-primary font-semibold ring-1 ring-primary'
              : 'border-border/80 bg-card hover:bg-muted text-foreground'
          }`}
        >
          <i className="fa-solid fa-pen-nib text-[11px]" />
          <span>Draw Signature</span>
        </button>

        {/* Direct Ink Color Picker: Single-click native color picker right there inline in toolbar */}
        <div
          onClick={() => colorInputRef.current?.click()}
          title="Change signature ink color (Default: Blue)"
          className={`px-2.5 py-1.5 rounded-md border border-border/80 bg-card hover:bg-muted text-foreground text-xs font-medium shadow-2xs hover:shadow-xs transition-colors cursor-pointer flex items-center gap-2 select-none ${
            readOnly ? 'opacity-40 pointer-events-none cursor-not-allowed' : ''
          }`}
        >
          <input
            ref={colorInputRef}
            type="color"
            value={penColor}
            disabled={readOnly}
            onClick={(e) => e.stopPropagation()}
            onChange={(e) => {
              e.stopPropagation();
              const val = e.target.value;
              if (val) {
                setPenColor(val);
                penColorRef.current = val;
                setIsDrawingMode(true);
              }
            }}
            aria-label="Choose signature ink color"
            className="w-4 h-4 p-0 border border-black/20 dark:border-white/20 rounded-full cursor-pointer bg-transparent overflow-hidden shrink-0 shadow-2xs transition-transform hover:scale-110 [&::-webkit-color-swatch-wrapper]:p-0 [&::-webkit-color-swatch]:border-0 [&::-webkit-color-swatch]:rounded-full [&::-moz-color-swatch]:border-0 [&::-moz-color-swatch]:rounded-full"
          />
          <span className="text-xs font-medium">Ink</span>
        </div>

        {/* Clear Signature strokes button: appears when user has drawn strokes */}
        {hasDrawnSignature && !readOnly && (
          <button
            type="button"
            onClick={handleClearSignature}
            title="Clear signature strokes (keeps stamp/base image)"
            className="px-3 py-1.5 rounded-md border border-border/80 bg-card hover:bg-destructive/10 hover:border-destructive/30 hover:text-destructive text-muted-foreground text-xs font-medium shadow-2xs hover:shadow-xs transition-colors cursor-pointer flex items-center gap-1.5"
          >
            <i className="fa-solid fa-eraser text-[11px]" />
            <span>Clear Signature</span>
          </button>
        )}

        {/* Clear All button: appears when stamp, base image, or drawn signature exists */}
        {hasAnyContent && !readOnly && (
          <button
            type="button"
            onClick={handleClearAll}
            title="Clear stamp and signature"
            className="px-3 py-1.5 rounded-md border border-border/80 bg-card hover:bg-destructive/10 hover:border-destructive/30 hover:text-destructive text-muted-foreground text-xs font-medium shadow-2xs hover:shadow-xs transition-colors cursor-pointer flex items-center gap-1.5"
          >
            <i className="fa-solid fa-trash-can text-[11px]" />
            <span>Clear All</span>
          </button>
        )}
      </div>

      {/* Bottom Label: Authority Signature title with expanded width & edit pencil */}
      {!hideTitleFields && (
        <div className="flex flex-col items-center justify-center w-full mt-3">
          <div className="flex items-center justify-center gap-1.5 w-full">
            <input
              ref={authTitleInputRef}
              type="text"
              name="seller_signature_label"
              value={authorityTitle}
              onChange={(e) => onAuthorityTitleChange(e.target.value)}
              disabled={readOnly}
              aria-label={`${partyType} authority title`}
              placeholder={authorityPlaceholder || 'Authorised Signature'}
              className={`font-bold text-center tracking-wider text-[14px] bg-transparent border-b-2 ${
                authorityError
                  ? 'border-solid border-brand-red text-brand-red'
                  : 'border-dotted border-primary/60 hover:border-primary focus:border-solid focus:border-primary'
              } focus:outline-none text-foreground py-0.5 px-2 w-full max-w-[280px] sm:max-w-[340px] transition-colors placeholder:text-[14px] placeholder:font-normal placeholder:text-muted-foreground/50`}
            />
            {!readOnly && (
              <button
                type="button"
                onClick={() => authTitleInputRef.current?.focus()}
                title="Edit label"
                className="text-primary hover:text-primary-hover transition-colors p-0.5 cursor-pointer disabled:opacity-40"
              >
                <i className="fa-solid fa-pen text-xs" />
              </button>
            )}
          </div>
          {authorityError && (
            <div className="w-full text-[11px] text-brand-red font-semibold px-2 py-1 tracking-tight flex items-center justify-center gap-1.5 mt-1 select-none animate-in fade-in duration-200">
              <i className="fa-solid fa-circle-exclamation text-[11px] shrink-0 text-brand-red" />
              <span className="text-brand-red">{authorityError}</span>
            </div>
          )}
        </div>
      )}

      {error && (
        <div className="w-full text-[11px] text-brand-red font-semibold px-2 py-1 tracking-tight flex items-center justify-center gap-1.5 mt-1 select-none animate-in fade-in duration-200">
          <i className="fa-solid fa-circle-exclamation text-[11px] shrink-0 text-brand-red" />
          <span className="text-brand-red">{error}</span>
        </div>
      )}
    </div>
  );
}

